// installStub writes an executable stub named name onto a fresh PATH entry
// and wires up the version and args-dump environment.
func installStub(t *testing.T, name, script, stubVersion string) (argsFile string) {
	t.Helper()
	binDir := t.TempDir()
	if err := os.WriteFile(filepath.Join(binDir, name), []byte(script), 0o755); err != nil { //nolint:gosec // a test stub must be executable
		t.Fatal(err)
	}
	t.Setenv("PATH", binDir+string(os.PathListSeparator)+os.Getenv("PATH"))

	argsFile = filepath.Join(t.TempDir(), "args")
	t.Setenv("STUB_ARGS_FILE", argsFile)
	t.Setenv("STUB_VERSION", stubVersion)
	return argsFile
}

// emptyPath points PATH at a directory holding nothing, so LookPath fails.
func emptyPath(t *testing.T) {
	t.Helper()
	t.Setenv("PATH", t.TempDir())
}

// stubArgs reads the invocation the stub recorded, one argument per line.
func stubArgs(t *testing.T, argsFile string) []string {
	t.Helper()
	data, err := os.ReadFile(argsFile)
	if err != nil {
		t.Fatalf("the stub recorded no arguments: %v", err)
	}
	return strings.Split(strings.TrimRight(string(data), "\n"), "\n")
}

// testConfig builds a config selecting the given backend at pin 1.2.3.
func testConfig(backend string, include, exclude []string) *config.Config {
	return &config.Config{
		// Provider and Auth are filled because the kiota backend derives its
		// --namespace-name through emit.FromConfig, which validates them.
		Provider: config.Provider{Name: "petstore", RegistryNamespace: "exampleco"},
		Auth:     config.Auth{Method: config.AuthBearerToken},
		SDK: config.SDK{
			Backend:        backend,
			BackendVersion: "1.2.3",
			ClientTypeName: "APIClient",
			IncludePaths:   include,
			ExcludePaths:   exclude,
		},
	}
}

