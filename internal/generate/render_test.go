func TestUnit_Render_RegistrationIsSortedAndComplete(t *testing.T) {
	t.Parallel()

	bp := pilot(t)

	// A second resource, added out of order, so the sort is exercised.
	second := bp.Resources[0]
	second.Key = "aaa"
	second.Name = "aaa"
	second.GoPackage = "aaa"
	second.GoPackageAlias = "v7Aaa"
	second.GoTypeName = "AaaResource"
	bp.Resources = append(bp.Resources, second)

	v := Registration(bp, RegistryKindResources, Options{BlueprintPath: "b", BlueprintSHA256: "s"})

	// The committed blueprint's non-dropped resources plus the one appended above
	// -- a dropped resource (the SDK-gated dashboard) registers nothing.
	want := 0
	for _, r := range bp.Resources {
		if !r.Drop {
			want++
		}
	}
	if len(v.Entries) != want {
		t.Fatalf("got %d entries, want %d", len(v.Entries), want)
	}
	// Sorted by alias, so the file does not depend on blueprint ordering.
	if !strings.HasPrefix(v.Entries[0], "v7Aaa.") {
		t.Errorf("entries are not sorted: %v", v.Entries)
	}
	if !strings.Contains(v.Imports, "v7Aaa ") || !strings.Contains(v.Imports, "v7Tag ") {
		t.Errorf("imports missing an alias:\n%s", v.Imports)
	}

	// A dropped resource must not be registered.
	bp.Resources[len(bp.Resources)-1].Drop = true
	if got := Registration(bp, RegistryKindResources, Options{}); len(got.Entries) != want-1 {
		t.Errorf("a dropped resource should not be registered: %v", got.Entries)
	}

	// Data sources register through the same path, sorted by the same rule.
	ds := Registration(bp, RegistryKindDataSources, Options{})
	if len(ds.Entries) != 2 {
		t.Fatalf("got %d data source entries, want 2: %v", len(ds.Entries), ds.Entries)
	}
	if !strings.HasPrefix(ds.Entries[0], "v7TagData.") {
		t.Errorf("data source entries are not sorted by alias: %v", ds.Entries)
	}
	if !strings.Contains(ds.Imports, "v7TagsData ") {
		t.Errorf("data source imports missing an alias:\n%s", ds.Imports)
	}

	// A dropped data source must not be registered either, and an empty list must
	// still render rather than failing.
	bp.DataSources[0].Drop = true
	bp.DataSources[1].Drop = true
	if got := Registration(bp, RegistryKindDataSources, Options{}); len(got.Entries) != 0 {
		t.Errorf("dropped data sources should not be registered: %v", got.Entries)
	}
}

func TestUnit_Render_Directories(t *testing.T) {
	t.Parallel()

	bp := pilot(t)
	r := bp.Resources[0]

	if got := ResourceDir(bp, r); got != "internal/services/resources/tags/v7/tag" {
		t.Errorf("ResourceDir = %q", got)
	}
	if got := ProviderDir(bp); got != "internal/provider" {
		t.Errorf("ProviderDir = %q", got)
	}

	// An empty component must not produce a doubled separator.
	r.ServiceGroup = ""
	if got := ResourceDir(bp, r); strings.Contains(got, "//") {
		t.Errorf("ResourceDir has a doubled separator: %q", got)
	}

	// Conventions are defaults, not requirements.
	bare := blueprint.Blueprint{}
	if got := ProviderDir(bare); got != "internal/provider" {
		t.Errorf("ProviderDir fallback = %q", got)
	}
	if got := DataSourceDir(bare, blueprint.DataSource{GoPackage: "x"}); !strings.HasSuffix(got, "datasources/x") {
		t.Errorf("DataSourceDir fallback = %q", got)
	}
}

