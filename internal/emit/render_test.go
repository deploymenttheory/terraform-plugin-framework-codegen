// testConfig builds a valid config for one backend and auth method.
func testConfig(backend, method string) *config.Config {
	cfg := &config.Config{
		Provider: config.Provider{Name: "petstore", RegistryNamespace: "exampleco"},
		SDK:      config.SDK{Backend: backend, ClientTypeName: "APIClient"},
		Auth:     config.Auth{Method: method},
	}
	if method == config.AuthAPIKeyHeader {
		cfg.Auth.APIKeyHeader = "X-Api-Key"
	}
	if method == config.AuthOAuth2ClientCredentials {
		cfg.Auth.TokenURL = "https://login.example.test/oauth2/token"
	}
	return cfg
}

// backends and methods enumerate the closed sets the provider core
// branches over.
var backends = []string{config.BackendKiota, config.BackendOpenAPIGenerator}

var methods = []string{
	config.AuthBearerToken,
	config.AuthAPIKeyHeader,
	config.AuthBasic,
	config.AuthOAuth2ClientCredentials,
	config.AuthGitHubApp,
}

// TestUnit_RenderProviderCore_EveryBackendAndAuthMethodRenders proves the
// whole template matrix: every combination renders, every .go file is
// gofmt-clean as rendered (RenderProviderCore refuses otherwise) and
// parses, every file carries the DO-NOT-EDIT header where a header is
// possible, and no file carries a doubled blank line or a missing final
// newline.
func TestUnit_RenderProviderCore_EveryBackendAndAuthMethodRenders(t *testing.T) {
	for _, backend := range backends {
		for _, method := range methods {
			t.Run(backend+"/"+method, func(t *testing.T) {
				pc, err := FromConfig(testConfig(backend, method), "https://api.example.test")
				if err != nil {
					t.Fatalf("FromConfig: %v", err)
				}

				files, err := RenderProviderCore(pc)
				if err != nil {
					t.Fatalf("RenderProviderCore: %v", err)
				}
				if len(files) == 0 {
					t.Fatal("RenderProviderCore returned no files")
				}

				fset := token.NewFileSet()
				for _, f := range files {
					content := string(f.Content)

					if !strings.HasSuffix(content, "\n") || strings.HasSuffix(content, "\n\n") {
						t.Errorf("%s does not end with exactly one newline", f.Path)
					}
					if strings.Contains(content, "\n\n\n") {
						t.Errorf("%s carries a doubled blank line", f.Path)
					}

					if strings.HasSuffix(f.Path, ".go") {
						if _, err := parser.ParseFile(fset, f.Path, f.Content, parser.AllErrors); err != nil {
							t.Errorf("%s does not parse: %v", f.Path, err)
						}
					}

					wantHeader := headerFor(f.Path)
					if wantHeader != "" && !strings.HasPrefix(content, wantHeader) {
						t.Errorf("%s does not start with the %q generated header", f.Path, wantHeader)
					}
					if wantHeader != "" && !strings.Contains(strings.SplitN(content, "\n", 2)[0], "DO NOT EDIT.") {
						t.Errorf("%s's first line does not carry DO NOT EDIT.", f.Path)
					}
				}
			})
		}
	}
}

// headerFor says which comment leader a path's generated header uses,
// empty for formats that cannot carry comments.
func headerFor(p string) string {
	switch {
	case strings.HasSuffix(p, ".json"):
		return ""
	case strings.HasSuffix(p, ".go"), p == "go.mod":
		return "// Code generated by tfpfgen from "
	default:
		return "# Code generated by tfpfgen from "
	}
}

// TestUnit_RenderProviderCore_OperatorEnvVarsCarryTheBareProviderPrefix proves the
// emitted provider configuration reads <PROVIDER>_* operator variables —
// bare, with no TF_ in front — and spells the token attribute api_token.
func TestUnit_RenderProviderCore_OperatorEnvVarsCarryTheBareProviderPrefix(t *testing.T) {
	for method, wants := range map[string][]string{
		config.AuthBearerToken: {
			`"api_token"`,
			"PETSTORE_ENDPOINT",
			"PETSTORE_API_TOKEN",
		},
		config.AuthAPIKeyHeader: {
			`"api_token"`,
			"PETSTORE_API_TOKEN",
		},
		config.AuthBasic: {
			`"username"`, `"password"`,
			"PETSTORE_USERNAME", "PETSTORE_PASSWORD",
		},
		config.AuthOAuth2ClientCredentials: {
			`"client_id"`, `"client_secret"`, `"token_url"`,
			"PETSTORE_CLIENT_ID", "PETSTORE_CLIENT_SECRET", "PETSTORE_TOKEN_URL",
		},
	} {
		pc, err := FromConfig(testConfig(config.BackendKiota, method), "")
		if err != nil {
			t.Fatalf("FromConfig(%s): %v", method, err)
		}
		files, err := RenderProviderCore(pc)
		if err != nil {
			t.Fatalf("RenderProviderCore(%s): %v", method, err)
		}

		var providerGo string
		for _, f := range files {
			if f.Path == "internal/provider/provider.go" {
				providerGo = string(f.Content)
			}
		}
		if providerGo == "" {
			t.Fatalf("%s render is missing internal/provider/provider.go", method)
		}
		for _, want := range wants {
			if !strings.Contains(providerGo, want) {
				t.Errorf("%s provider.go does not carry %s", method, want)
			}
		}
		if strings.Contains(providerGo, `"TF_PETSTORE_`) {
			t.Errorf("%s provider.go still reads a TF_-prefixed operator variable", method)
		}
	}
}

// TestUnit_RenderProviderCore_ClientOptionsPacesTheRetryLoops proves the
// emitted provider carries the client_options block, resolves both knobs
// against the environment, and hands the result to the one place the retry
// loops read their cadence from. A knob the practitioner can set that
// reaches nothing is worse than no knob at all, so all three halves are
// pinned together.
func TestUnit_RenderProviderCore_ClientOptionsPacesTheRetryLoops(t *testing.T) {
	pc, err := FromConfig(testConfig(config.BackendKiota, config.AuthBearerToken), "")
	if err != nil {
		t.Fatalf("FromConfig: %v", err)
	}
	files, err := RenderProviderCore(pc)
	if err != nil {
		t.Fatalf("RenderProviderCore: %v", err)
	}

	rendered := make(map[string]string, len(files))
	for _, f := range files {
		rendered[f.Path] = string(f.Content)
	}

	providerGo, ok := rendered["internal/provider/provider.go"]
	if !ok {
		t.Fatal("the render is missing internal/provider/provider.go")
	}
	for _, want := range []string{
		`"client_options": schema.SingleNestedAttribute{`,
		`"read_retry_delay_seconds": schema.Int64Attribute{`,
		`"delete_retry_delay_seconds": schema.Int64Attribute{`,
		`secondsOrEnv(readRetryDelay, "PETSTORE_READ_RETRY_DELAY_SECONDS")`,
		`secondsOrEnv(deleteRetryDelay, "PETSTORE_DELETE_RETRY_DELAY_SECONDS")`,
		"crud.SetRetryCadence(",
	} {
		if !strings.Contains(providerGo, want) {
			t.Errorf("provider.go does not carry %s", want)
		}
	}

	retryGo, ok := rendered["internal/services/common/crud/retry.go"]
	if !ok {
		t.Fatal("the render is missing internal/services/common/crud/retry.go")
	}
	for _, want := range []string{
		"func SetRetryCadence(",
		"DefaultReadRetryInterval   = 2 * time.Second",
		"DefaultDeleteRetryInterval = 10 * time.Second",
	} {
		if !strings.Contains(retryGo, want) {
			t.Errorf("crud/retry.go does not carry %s", want)
		}
	}

	// The loops must read the installed cadence, not a literal of their own.
	for path, want := range map[string]string{
		"internal/services/common/crud/read_with_retry.go":   "opts.Interval = readRetryInterval()",
		"internal/services/common/crud/delete_with_retry.go": "opts.Interval = deleteRetryInterval()",
	} {
		if !strings.Contains(rendered[path], want) {
			t.Errorf("%s does not read the installed cadence (%s)", path, want)
		}
	}
}

// TestUnit_RenderProviderCore_DialectSelectionIsExclusive proves each
// backend gets its own dialect files and never the other's.
func TestUnit_RenderProviderCore_DialectSelectionIsExclusive(t *testing.T) {
	renderPaths := func(backend string) map[string]bool {
		t.Helper()
		pc, err := FromConfig(testConfig(backend, config.AuthBearerToken), "")
		if err != nil {
			t.Fatalf("FromConfig: %v", err)
		}
		files, err := RenderProviderCore(pc)
		if err != nil {
			t.Fatalf("RenderProviderCore: %v", err)
		}
		paths := make(map[string]bool, len(files))
		for _, f := range files {
			paths[f.Path] = true
		}
		return paths
	}

	kiota := renderPaths(config.BackendKiota)
	openapi := renderPaths(config.BackendOpenAPIGenerator)

	for path, wantIn := range map[string]map[string]bool{
		"internal/client/client_kiota.go":                              kiota,
		"internal/services/common/errors/extract_kiota.go":             kiota,
		"internal/services/common/convert/convert_kiota.go":            kiota,
		"internal/client/client_openapigenerator.go":                   openapi,
		"internal/services/common/errors/extract_openapigenerator.go":  openapi,
		"internal/services/common/convert/convert_openapigenerator.go": openapi,
	} {
		if !wantIn[path] {
			t.Errorf("%s is missing from its own backend's render", path)
		}
	}
	for _, path := range []string{
		"internal/client/client_openapigenerator.go",
		"internal/services/common/errors/extract_openapigenerator.go",
		"internal/services/common/convert/convert_openapigenerator.go",
	} {
		if kiota[path] {
			t.Errorf("%s leaked into the kiota render", path)
		}
	}
	for _, path := range []string{
		"internal/client/client_kiota.go",
		"internal/services/common/errors/extract_kiota.go",
		"internal/services/common/convert/convert_kiota.go",
	} {
		if openapi[path] {
			t.Errorf("%s leaked into the openapi-generator render", path)
		}
	}
}

// TestUnit_RenderProviderCore_RegistriesCarryTheSentinels proves every
// registry file carries both machine-append sentinels `provider generate`
// targets.
func TestUnit_RenderProviderCore_RegistriesCarryTheSentinels(t *testing.T) {
	pc, err := FromConfig(testConfig(config.BackendKiota, config.AuthBearerToken), "")
	if err != nil {
		t.Fatalf("FromConfig: %v", err)
	}
	files, err := RenderProviderCore(pc)
	if err != nil {
		t.Fatalf("RenderProviderCore: %v", err)
	}

	byPath := make(map[string]string, len(files))
	for _, f := range files {
		byPath[f.Path] = string(f.Content)
	}

	for file, kind := range map[string]string{
		"internal/provider/resources.go":      "resources",
		"internal/provider/datasources.go":    "datasources",
		"internal/provider/list_resources.go": "list_resources",
		"internal/provider/actions.go":        "actions",
	} {
		content, ok := byPath[file]
		if !ok {
			t.Errorf("%s is missing from the render", file)
			continue
		}
		for _, sentinel := range []string{
			"// tfpfgen:" + kind + ":imports",
			"// tfpfgen:" + kind + ":registrations",
		} {
			if !strings.Contains(content, sentinel) {
				t.Errorf("%s does not carry the %q sentinel", file, sentinel)
			}
		}
	}
}

// TestUnit_RenderProviderCore_RefusesAnInconsistentContext proves the
// context check runs before any template does.
func TestUnit_RenderProviderCore_RefusesAnInconsistentContext(t *testing.T) {
	if _, err := RenderProviderCore(ProviderCore{}); err == nil {
		t.Fatal("RenderProviderCore accepted a zero context")
	}

	pc, err := FromConfig(testConfig(config.BackendKiota, config.AuthBearerToken), "")
	if err != nil {
		t.Fatalf("FromConfig: %v", err)
	}
	pc.BackendOpenAPIGenerator = true // two backends at once
	if _, err := RenderProviderCore(pc); err == nil {
		t.Fatal("RenderProviderCore accepted two backends")
	}

	pc, err = FromConfig(testConfig(config.BackendKiota, config.AuthBearerToken), "")
	if err != nil {
		t.Fatalf("FromConfig: %v", err)
	}
	pc.AuthBasic = true // two auth methods at once
	if _, err := RenderProviderCore(pc); err == nil {
		t.Fatal("RenderProviderCore accepted two auth methods")
	}
}

// validContext returns a valid context for exercising renderProviderCore
// against crafted filesystems.
func validContext(t *testing.T) ProviderCore {
	t.Helper()
	pc, err := FromConfig(testConfig(config.BackendKiota, config.AuthBearerToken), "")
	if err != nil {
		t.Fatalf("FromConfig: %v", err)
	}
	return pc
}

// testPartial is a minimal valid header partial for crafted filesystems.
const testPartial = `{{ define "header" }}// Code generated by tfpfgen from {{ .Source }}. DO NOT EDIT.{{ end }}
{{ define "hashheader" }}# Code generated by tfpfgen from {{ .Source }}. DO NOT EDIT.{{ end }}
`

// TestUnit_RenderProviderCore_ReportsTemplateProblemsByName proves each
// failure mode names the template it came from.
func TestUnit_RenderProviderCore_ReportsTemplateProblemsByName(t *testing.T) {
	cases := []struct {
		name    string
		fsys    fstest.MapFS
		wantErr string
	}{
		{
			name:    "missing header partial",
			fsys:    fstest.MapFS{"provider-core/main.go.tmpl": &fstest.MapFile{Data: []byte("package main\n")}},
			wantErr: "header partial",
		},
		{
			name: "unparseable template",
			fsys: fstest.MapFS{
				"provider-core/_header.tmpl": &fstest.MapFile{Data: []byte(testPartial)},
				"provider-core/bad.go.tmpl":  &fstest.MapFile{Data: []byte("{{ if }}")},
			},
			wantErr: "provider-core/bad.go.tmpl",
		},
		{
			name: "missing field",
			fsys: fstest.MapFS{
				"provider-core/_header.tmpl": &fstest.MapFile{Data: []byte(testPartial)},
				"provider-core/bad.go.tmpl":  &fstest.MapFile{Data: []byte("{{ .NoSuchField }}")},
			},
			wantErr: "provider-core/bad.go.tmpl",
		},
		{
			name: "renders unparseable go",
			fsys: fstest.MapFS{
				"provider-core/_header.tmpl": &fstest.MapFile{Data: []byte(testPartial)},
				"provider-core/bad.go.tmpl":  &fstest.MapFile{Data: []byte("this is not go\n")},
			},
			wantErr: "does not parse",
		},
		{
			name: "renders gofmt-unclean go",
			fsys: fstest.MapFS{
				"provider-core/_header.tmpl": &fstest.MapFile{Data: []byte(testPartial)},
				"provider-core/bad.go.tmpl":  &fstest.MapFile{Data: []byte("package p\n\nfunc f() {\n  return\n}\n")},
			},
			wantErr: "gofmt-clean",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := renderProviderCore(tc.fsys, validContext(t))
			if err == nil {
				t.Fatalf("renderProviderCore accepted the %s tree", tc.name)
			}
			if !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("error %q does not mention %q", err, tc.wantErr)
			}
		})
	}
}

// TestUnit_RenderProviderCore_NonGoFilesAreNotHeldToGofmt proves a
// crafted non-Go file passes through with only whitespace bookkeeping.
func TestUnit_RenderProviderCore_NonGoFilesAreNotHeldToGofmt(t *testing.T) {
	fsys := fstest.MapFS{
		"provider-core/_header.tmpl": &fstest.MapFile{Data: []byte(testPartial)},
		"provider-core/notes.txt.tmpl": &fstest.MapFile{
			Data: []byte("{{ template \"hashheader\" . }}\n\n\n\nplain   text\n\n\n"),
		},
	}

	files, err := renderProviderCore(fsys, validContext(t))
	if err != nil {
		t.Fatalf("renderProviderCore: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("got %d files, want 1", len(files))
	}
	got := string(files[0].Content)
	want := "# Code generated by tfpfgen from provider-core/notes.txt.tmpl. DO NOT EDIT.\n\nplain   text\n"
	if got != want {
		t.Fatalf("got %q, want %q", got, want)
	}
}

// TestUnit_RenderProviderCore_BothDialectsCarryWhatTheAPISaid proves neither
// generated extractor reports a refusal as the SDK's own constant when the
// response body carried the API's words.
func TestUnit_RenderProviderCore_BothDialectsCarryWhatTheAPISaid(t *testing.T) {
	for backend, want := range map[string][]string{
		// kiota deserializes the body into the properties the document
		// declared and leaves the embedded ApiError's message unset, so the
		// getters are the only place the API's words survive.
		config.BackendKiota: {
			"kiotaSilence",
			"GetDetail() *string",
			"GetTitle() *string",
			"GetAdditionalData() map[string]any",
			"validationErrors",
		},
		// openapi-generator hands the raw body over, so reading it is enough.
		config.BackendOpenAPIGenerator: {"apiErr.Body()"},
	} {
		pc, err := FromConfig(testConfig(backend, config.AuthBearerToken), "")
		if err != nil {
			t.Fatalf("FromConfig(%s): %v", backend, err)
		}
		files, err := RenderProviderCore(pc)
		if err != nil {
			t.Fatalf("RenderProviderCore(%s): %v", backend, err)
		}
		var extractor string
		for _, f := range files {
			if strings.HasPrefix(f.Path, "internal/services/common/errors/extract_") {
				extractor = string(f.Content)
			}
		}
		if extractor == "" {
			t.Fatalf("%s rendered no extractor", backend)
		}
		for _, fragment := range want {
			if !strings.Contains(extractor, fragment) {
				t.Errorf("%s extractor does not read %q", backend, fragment)
			}
		}
	}
}
