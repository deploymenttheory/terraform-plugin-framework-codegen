// fakeKiotaVersion is what the stub binary reports and stamps into its lock.
const fakeKiotaVersion = "1.99.0"

// fakeKiota puts a stub kiota first on PATH. The stub is deterministic: given
// the same arguments it writes the same tree, which is exactly the property
// the real generator has and the -check path depends on.
func fakeKiota(t *testing.T) {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("the stub kiota is a shell script")
	}

	dir := t.TempDir()
	script := `#!/bin/sh
case "$1" in
--version)
  echo "` + fakeKiotaVersion + `+stub"
  ;;
info)
  echo '{"dependencies":[{"name":"github.com/microsoft/kiota-bundle-go","version":"v1.4.3","dependencyType":"bundle"}]}'
  ;;
generate)
  out=""; ns=""; class=""; desc=""
  prev=""
  for a in "$@"; do
    case "$prev" in
    --output) out="$a" ;;
    --namespace-name) ns="$a" ;;
    --class-name) class="$a" ;;
    --openapi) desc="$a" ;;
    esac
    prev="$a"
  done
  mkdir -p "$out/models"
  base=$(basename "$ns")
  cat > "$out/client.go" <<EOF
// Code generated by Microsoft Kiota - DO NOT EDIT.
// namespace: $ns
package $base

type $class struct{}
EOF
  cat > "$out/models/model.go" <<EOF
// Code generated by Microsoft Kiota - DO NOT EDIT.
package models

type Thing struct{ value *string }

func (t *Thing) GetValue() *string  { return t.value }
func (t *Thing) SetValue(v *string) { t.value = v }
EOF
  hash=$(cksum "$desc" | cut -d' ' -f1)
  cat > "$out/kiota-lock.json" <<EOF
{"descriptionHash":"$hash","kiotaVersion":"` + fakeKiotaVersion + `","clientClassName":"$class","clientNamespaceName":"$ns"}
EOF
  ;;
esac
`
	path := filepath.Join(dir, "kiota")
	if err := os.WriteFile(path, []byte(script), 0o700); err != nil { //nolint:gosec // executable stub
		t.Fatal(err)
	}
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
}

// pinnedSnapshot writes a real, checksummed snapshot for the stub to read.
func pinnedSnapshot(t *testing.T) string {
	t.Helper()

	root := filepath.Join(t.TempDir(), "openapi", "test")
	doc := []byte("openapi: 3.0.0\ninfo:\n  title: t\n  version: \"1\"\npaths: {}\n")
	sum := sha256.Sum256(doc)

	if _, err := snapshot.Pin(root, doc, snapshot.Metadata{
		Version:   "1",
		SHA256:    hex.EncodeToString(sum[:]),
		SourceURL: "https://example.invalid/openapi.yaml",
		FetchedAt: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC),
	}); err != nil {
		t.Fatal(err)
	}
	return root
}

// sdkModuleRoot builds an enclosing Go module for embed-mode derivation.
func sdkModuleRoot(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "go.mod"),
		[]byte("module example.com/prov\n\ngo 1.25\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	return root
}

func TestUnit_CLI_SDK_RequiredFlags(t *testing.T) {
	quiet(t)

	if err := runSDKGenerate(nil); err == nil {
		t.Error("expected -out to be required")
	}
	if err := runSDKGenerate([]string{"-out", t.TempDir(), "-mode", "sideways"}); err == nil {
		t.Error("expected an unknown mode to be refused")
	}
	err := runSDKGenerate([]string{"-out", t.TempDir(), "-mode", "external"})
	if err == nil || !strings.Contains(err.Error(), "-module is required") {
		t.Errorf("external mode must demand -module, got: %v", err)
	}
}

func TestUnit_CLI_SDK_GenerateEmbeds(t *testing.T) {
	quiet(t)
	fakeKiota(t)

	root := sdkModuleRoot(t)
	out := filepath.Join(root, "internal", "sdk")
	openapiDir := pinnedSnapshot(t)

	err := runSDKGenerate([]string{"-openapi-dir", openapiDir, "-out", out, "-client-name", "TeClient"})
	if err != nil {
		t.Fatalf("sdk generate: %v", err)
	}

	// The stub records kiota's -n in the generated client; embed mode must have
	// derived it from the enclosing module plus the relative path.
	client, err := os.ReadFile(filepath.Join(out, "client.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(client), "namespace: example.com/prov/internal/sdk") {
		t.Errorf("embed mode derived the wrong module:\n%s", client)
	}

	if _, err := os.Stat(filepath.Join(out, "kiota-lock.json")); err != nil {
		t.Errorf("the lock file was not written: %v", err)
	}
	// gofumpt ran over the stub's output: the format pass leaves valid Go valid.
	if _, err := os.Stat(filepath.Join(out, "models", "model.go")); err != nil {
		t.Errorf("models were not written: %v", err)
	}
}

func TestUnit_CLI_SDK_VersionGateRefuses(t *testing.T) {
	quiet(t)
	fakeKiota(t)

	root := sdkModuleRoot(t)
	out := filepath.Join(root, "internal", "sdk")
	if err := os.MkdirAll(out, 0o750); err != nil {
		t.Fatal(err)
	}
	// A lock from a different kiota than the stub reports.
	if err := os.WriteFile(filepath.Join(out, "kiota-lock.json"),
		[]byte(`{"kiotaVersion":"0.0.1"}`), 0o600); err != nil {
		t.Fatal(err)
	}

	err := runSDKGenerate([]string{"-openapi-dir", pinnedSnapshot(t), "-out", out})
	if err == nil || !strings.Contains(err.Error(), "0.0.1") || !strings.Contains(err.Error(), fakeKiotaVersion) {
		t.Errorf("the version gate must name both versions, got: %v", err)
	}
}

func TestUnit_CLI_SDK_CheckCatchesDriftAndHandEdits(t *testing.T) {
	quiet(t)
	fakeKiota(t)

	root := sdkModuleRoot(t)
	out := filepath.Join(root, "internal", "sdk")
	openapiDir := pinnedSnapshot(t)

	gen := []string{"-openapi-dir", openapiDir, "-out", out}
	if err := runSDKGenerate(gen); err != nil {
		t.Fatalf("sdk generate: %v", err)
	}

	check := []string{"-openapi-dir", openapiDir, "-out", out, "-check"}
	if err := runSDKGenerate(check); err != nil {
		t.Fatalf("a freshly generated tree must pass -check: %v", err)
	}

	// A hand edit to a generated file is drift.
	edited := filepath.Join(out, "models", "model.go")
	if err := os.WriteFile(edited, []byte("package models\n\n// edited by hand\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := runSDKGenerate(check); err == nil {
		t.Error("-check must fail on a hand-edited generated file")
	}

	// Regenerating repairs it.
	if err := runSDKGenerate(gen); err != nil {
		t.Fatalf("regenerate: %v", err)
	}
	if err := runSDKGenerate(check); err != nil {
		t.Errorf("-check must pass again after regeneration: %v", err)
	}
}

func TestUnit_CLI_SDK_ExternalEmitsItsOwnModule(t *testing.T) {
	quiet(t)
	fakeKiota(t)

	out := filepath.Join(t.TempDir(), "sdks", "test")
	err := runSDKGenerate([]string{
		"-openapi-dir", pinnedSnapshot(t), "-out", out,
		"-mode", "external", "-module", "example.com/sdktest",
	})
	if err != nil {
		t.Fatalf("sdk generate -mode external: %v", err)
	}

	mod, err := os.ReadFile(filepath.Join(out, "go.mod"))
	if err != nil {
		t.Fatalf("external mode must emit a go.mod: %v", err)
	}
	if !strings.Contains(string(mod), "module example.com/sdktest") {
		t.Errorf("go.mod carries the wrong module directive:\n%s", mod)
	}
}

func TestUnit_CLI_SDK_DryRunRunsNothing(t *testing.T) {
	quiet(t)
	fakeKiota(t)

	root := sdkModuleRoot(t)
	out := filepath.Join(root, "internal", "sdk")

	err := runSDKGenerate([]string{"-openapi-dir", pinnedSnapshot(t), "-out", out, "-dry-run"})
	if err != nil {
		t.Fatalf("dry run: %v", err)
	}
	if _, err := os.Stat(out); !os.IsNotExist(err) {
		t.Error("a dry run must generate nothing")
	}
}
